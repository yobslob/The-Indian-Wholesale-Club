#!/usr/bin/env node
/**
 * scripts/gen-db-types.mjs: writes packages/db/src/database.types.ts from the
 * LOCAL Supabase schema (Docker running + `npx supabase start`).
 *
 * Run after every migration change:  pnpm db:types
 * Written by Node (UTF-8, LF), not a shell redirect: Windows PowerShell's `>`
 * produces UTF-16, which breaks TypeScript. The output is generated. Never edit it by hand.
 */
import { spawnSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const OUT = 'packages/db/src/database.types.ts';

const result = spawnSync('npx supabase gen types --lang=typescript --local --schema public', {
  shell: true,
  encoding: 'utf8',
  maxBuffer: 50 * 1024 * 1024,
});

if (result.status !== 0 || !result.stdout.includes('export type Database')) {
  console.error(result.stderr || result.stdout || 'supabase gen types failed');
  console.error('\nIs Docker running and local Supabase started (`npx supabase start`)?');
  process.exit(1);
}

const header =
  '// GENERATED by `pnpm db:types` (supabase gen types --local) from supabase/migrations.\n' +
  '// Do not edit by hand. Regenerate after every schema change.\n\n';
writeFileSync(OUT, header + result.stdout.replace(/\r\n/g, '\n'), 'utf8');
console.log(`Wrote ${OUT}`);
