#!/usr/bin/env node
/**
 * scripts/build-us-map.mjs: builds the small US map of the flight (apps/web/features/visuals/flight.tsx; founder
 * 2026-10-30: "instead of a hut make US border outlined in states").
 *
 * Source: `states-albers-10m.json` from the us-atlas package (https://github.com/topojson/us-atlas, ISC; the US Census
 * Bureau's cartographic boundaries, public domain), already projected (Albers USA). Download it, then:
 *   node scripts/build-us-map.mjs <path to states-albers-10m.json>
 *
 * Writes apps/web/features/visuals/us-map.ts: the 48 contiguous states and DC (Alaska and Hawaii are insets too small
 * to read at this size) as two paths, the country's border and the lines between the states, simplified
 * (Douglas-Peucker) and scaled to 300 units wide, about 6 KB. Dependency-free.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const file = process.argv[2];
if (!file) throw new Error('usage: node scripts/build-us-map.mjs <states-albers-10m.json>');
const topo = JSON.parse(readFileSync(file, 'utf8'));
const LEAVE_OUT = new Set(['Alaska', 'Hawaii', 'Puerto Rico']);
const WIDTH = 300;
const TOLERANCE = 0.9; // in output units

// --- arcs: quantized and delta-encoded → absolute points
const [sx, sy] = topo.transform.scale;
const [tx, ty] = topo.transform.translate;
const arcs = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * sx + tx, y * sy + ty];
  });
});

// --- how many kept states use each arc: once = the country's border, twice = between two states
const uses = new Map();
for (const g of topo.objects.states.geometries) {
  if (LEAVE_OUT.has(g.properties?.name)) continue;
  const polys = g.type === 'Polygon' ? [g.arcs] : g.arcs;
  for (const ring of polys.flat()) for (const i of ring) {
    const a = i < 0 ? ~i : i;
    uses.set(a, (uses.get(a) ?? 0) + 1);
  }
}

// --- bounds of what is kept, then scale to WIDTH
let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
for (const a of uses.keys()) for (const [x, y] of arcs[a]) {
  minX = Math.min(minX, x); minY = Math.min(minY, y); maxX = Math.max(maxX, x); maxY = Math.max(maxY, y);
}
const k = WIDTH / (maxX - minX);
const height = Math.ceil((maxY - minY) * k);
const scaled = (pts) => pts.map(([x, y]) => [(x - minX) * k, (y - minY) * k]);

function simplify(pts) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [s, e] = stack.pop();
    const [x1, y1] = pts[s], [x2, y2] = pts[e];
    const len = Math.hypot(x2 - x1, y2 - y1) || 1;
    let far = -1, best = 0;
    for (let i = s + 1; i < e; i++) {
      const d = Math.abs((x2 - x1) * (y1 - pts[i][1]) - (x1 - pts[i][0]) * (y2 - y1)) / len;
      if (d > best) { best = d; far = i; }
    }
    if (best > TOLERANCE && far > 0) { keep[far] = 1; stack.push([s, far], [far, e]); }
  }
  return pts.filter((_, i) => keep[i]);
}

const r = (n) => Math.round(n * 2) / 2; // half units: crisp enough, short
function pathOf(list) {
  let d = '';
  for (const a of list) {
    const pts = simplify(scaled(arcs[a])).map(([x, y]) => [r(x), r(y)]);
    // an arc that shrank to a dot says nothing
    if (pts.length < 2 || (pts.length === 2 && pts[0][0] === pts[1][0] && pts[0][1] === pts[1][1])) continue;
    d += `M${pts[0][0]} ${pts[0][1]}` + pts.slice(1).map(([x, y]) => `L${x} ${y}`).join('');
  }
  return d;
}
const border = pathOf([...uses].filter(([, n]) => n === 1).map(([a]) => a));
const states = pathOf([...uses].filter(([, n]) => n > 1).map(([a]) => a));

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '../apps/web/features/visuals/us-map.ts');
writeFileSync(
  out,
  `/**
 * The 48 contiguous states and DC, for the flight's landing (founder 2026-10-30): the country's border and the lines
 * between its states. Generated by scripts/build-us-map.mjs from us-atlas (US Census Bureau boundaries, public domain);
 * do not edit by hand.
 */
export const US_MAP = {
  viewBox: '0 0 ${WIDTH} ${height}',
  border: '${border}',
  states: '${states}',
} as const;
`,
);
console.log(`us-map.ts: ${WIDTH} × ${height}, border ${border.length} chars, states ${states.length} chars`);
